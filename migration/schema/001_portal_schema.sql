-- ===========================================================================
-- Parent's Portal — PostgreSQL schema, ported column by column from
-- database/schema.sql (MySQL 8.0.43, utf8mb4_unicode_ci) on 2026-10-19.
--
-- Target: PostgreSQL 17 (Supabase) — rehearsed on embedded PostgreSQL 17.10.
-- Apply as the migration/restore role on an EMPTY target (scripts/apply-schema.js
-- refuses a target that already has the `portal` schema). Not idempotent on
-- purpose: a second run must fail loudly rather than half-apply.
--
-- Column-level mapping, with the reasons, is docs/02_CONTRACTS.md. In short:
--   INT UNSIGNED id          -> integer GENERATED BY DEFAULT AS IDENTITY
--                               (explicit ids are loaded by the transfer; the
--                               sequence is then set to the MySQL
--                               AUTO_INCREMENT value, empty tables included)
--   INT/TINYINT UNSIGNED     -> integer / smallint + CHECK (>= 0) where the
--                               value is a quantity (never for an id/FK)
--   TINYINT(1) boolean-like  -> smallint 0/1 + CHECK (col IN (0, 1)); the API
--                               keeps answering 0/1 (source values validated:
--                               only 0 and 1 exist; every application write
--                               binds a number or a literal 0/1)
--   ENUM                     -> a PostgreSQL enum type (same labels, same
--                               declaration order, so ORDER BY sorts as MySQL
--                               sorts an ENUM by index)
--   DECIMAL(5,2)             -> numeric(5,2) (pg returns the string '88.05')
--   DATE                     -> date (returned as 'YYYY-MM-DD' by lib/pg.js)
--   TIMESTAMP                -> timestamptz(0); TIMESTAMP(3) -> timestamptz(3)
--   DEFAULT CURRENT_TIMESTAMP-> DEFAULT portal.now_s() (statement time,
--                               truncated to the second like MySQL NOW())
--   ON UPDATE CURRENT_TIMESTAMP -> trigger portal.touch_updated_at(), which
--                               bumps only when another column really changed
--                               and leaves an explicitly SET updated_at alone
--   utf8mb4_unicode_ci       -> collation portal.ci (ICU und-u-ks-level1,
--                               nondeterministic) on the key/lookup columns
--                               that depend on case-insensitive equality;
--                               everything else is the database default
--   FOREIGN KEY              -> same names, same ON DELETE rules, DEFERRABLE
--                               INITIALLY IMMEDIATE (immediate in the app;
--                               deferred only inside the transfer's load
--                               transaction so the users <-> students cycle
--                               and any load order work)
--   MySQL's auto FK indexes  -> created explicitly with the same fk_* names
-- ===========================================================================

CREATE SCHEMA portal;
SET search_path = portal, pg_catalog;

-- ---------------------------------------------------------------------------
-- Collation. ICU when the server has it (Supabase does), else a named copy of
-- the database default so the DDL still applies and the gap is visible in
-- the collation's own comment (scripts/semantics.js reports which it got).
-- ---------------------------------------------------------------------------
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_collation WHERE collprovider = 'i') THEN
    EXECUTE $c$CREATE COLLATION portal.ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false)$c$;
    EXECUTE $c$COMMENT ON COLLATION portal.ci IS 'ICU und-u-ks-level1, nondeterministic: case- and accent-insensitive equality, the closest match to MySQL utf8mb4_unicode_ci (primary strength). Trailing spaces are significant here (MySQL PAD SPACE is not reproduced). LIKE on these columns needs an explicit deterministic collation before PostgreSQL 18.'$c$;
  ELSE
    EXECUTE $c$CREATE COLLATION portal.ci FROM "default"$c$;
    EXECUTE $c$COMMENT ON COLLATION portal.ci IS 'FALLBACK - this server has no ICU: portal.ci is the database default (case-sensitive). Lookups that relied on utf8mb4_unicode_ci are NOT case-insensitive on this target.'$c$;
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- Time. MySQL NOW() / CURRENT_TIMESTAMP is the START OF THE STATEMENT with
-- whole-second resolution; now() in PostgreSQL is the start of the
-- TRANSACTION with microseconds, and a timestamptz(0) column ROUNDS a
-- fractional input. Both helpers truncate (never round) and use statement
-- time, so a ported `NOW()` is `portal.now_s()` and a `NOW(3)` is
-- `portal.now_ms()`, inside or outside a transaction.
-- ---------------------------------------------------------------------------
CREATE FUNCTION portal.now_s() RETURNS timestamptz
  LANGUAGE sql STABLE AS $$ SELECT date_trunc('second', statement_timestamp()) $$;
CREATE FUNCTION portal.now_ms() RETURNS timestamptz
  LANGUAGE sql STABLE AS $$ SELECT date_trunc('milliseconds', statement_timestamp()) $$;

-- MySQL's ON UPDATE CURRENT_TIMESTAMP, exactly: the column is bumped only if
-- some OTHER column's value actually changed, and a statement that sets
-- updated_at itself wins. A no-op UPDATE (same values) does not bump.
CREATE FUNCTION portal.touch_updated_at() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.updated_at IS DISTINCT FROM OLD.updated_at THEN
    RETURN NEW;
  END IF;
  IF (to_jsonb(NEW) - 'updated_at') IS DISTINCT FROM (to_jsonb(OLD) - 'updated_at') THEN
    NEW.updated_at := portal.now_s();
  END IF;
  RETURN NEW;
END $$;

