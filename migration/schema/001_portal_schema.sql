-- ---------------------------------------------------------------------------
-- Foreign keys — the 33 of schema.sql, same names, same ON DELETE rules.
-- DEFERRABLE INITIALLY IMMEDIATE: the application sees immediate checks; the
-- transfer runs SET CONSTRAINTS ALL DEFERRED inside its single load
-- transaction (users <-> students reference each other).
-- ---------------------------------------------------------------------------
ALTER TABLE portal.users
  ADD CONSTRAINT fk_users_student FOREIGN KEY (student_id) REFERENCES portal.students(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  ADD CONSTRAINT fk_users_created_by FOREIGN KEY (created_by) REFERENCES portal.users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  ADD CONSTRAINT fk_users_approved_by FOREIGN KEY (approved_by) REFERENCES portal.users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE portal.students
  ADD CONSTRAINT fk_students_created_by FOREIGN KEY (created_by) REFERENCES portal.users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  ADD CONSTRAINT fk_students_section FOREIGN KEY (section_id) REFERENCES portal.sections(id) ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE portal.sections
  ADD CONSTRAINT fk_sections_adviser FOREIGN KEY (adviser_id) REFERENCES portal.users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE;

